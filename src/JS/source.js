  function stopTimer() {
    if (timerInterval) { clearInterval(timerInterval); timerInterval = null; }
  }

  function startTimer() {
    if (timerInterval) stopTimer();
    timerInterval = setInterval(() => {
      if (!examActive) return;
      if (secondsLeft <= 1) {
        secondsLeft = 0;
        updateTimerUI();
        stopTimer();
        if (examActive && !isFinalizing) autoSubmitDueToTime();
      } else {
        secondsLeft--;
        updateTimerUI();
      }
    }, 700);
  }

