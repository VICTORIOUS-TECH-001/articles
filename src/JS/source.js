      const statusClass = isAnswered ? 'nav-answered' : 'nav-unanswered';
      const activeClass = (i === currentQIndex) ? 'nav-active' : '';
      html += `<button class="nav-q-btn ${statusClass} ${activeClass}" data-qidx="${i}">${i+1}</button>`;
